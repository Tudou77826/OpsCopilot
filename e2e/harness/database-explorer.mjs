import { ensureMySQLJDBC } from './database-driver.mjs';
// Real MySQL / Wails explorer regression. Only isolated local fixture connections are saved.
import { chromium, expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const runtimeRoot = fileURLToPath(new URL('../.runtime/database-workspace/', import.meta.url));
const evidence = `${runtimeRoot}/evidence`;
await mkdir(evidence, { recursive: true });
const endpoint = JSON.parse((await readFile(`${runtimeRoot}/mysql-endpoint.json`, 'utf8')).replace(/^\uFEFF/, ''));
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1200, height: 833 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const sessions = [];
const checks = {};
try {
  await page.goto('http://127.0.0.1:34115/');
  await page.waitForFunction(() => window.go?.main?.App?.DatabaseGenerateSQL);
  await page.exposeFunction('recordExplorerSession', id => sessions.push(id));
  const driverId = await ensureMySQLJDBC(page);
  const profiles = await page.evaluate(async config => {
    const api = window.go.main.App;
    const original = api.DatabaseConnect;
    api.DatabaseConnect = async (...args) => { const session = await original(...args); await window.recordExplorerSession(session.id); return session; };
    const oldProfiles = await api.DatabaseProfiles();
    const out = [];
    for (const name of ['本地 MySQL · 体验库', '本地 MySQL · 对照连接']) {
      const old = oldProfiles.find(p => p.name === name);
      out.push(await api.DatabaseSave({ ...old, id: old?.id ?? '', revision: old?.revision ?? 0, name, environment: '测试', group: '本地体验', engine: 'jdbc', driverId: config.driverId, jdbcAllowPublicKeyRetrieval: true, gatewayMode: 'auto', host: config.host, port: config.port, user: config.user, database: config.database, password: config.password, tls: 'off', readOnly: old?.readOnly ?? true, gatewayId: '' }));
    }
    const query = api.DatabaseQuery;
    window.explorerQueryCount = 0;
    api.DatabaseQuery = (...args) => { window.explorerQueryCount++; return query(...args); };
    return out;
  }, { ...endpoint, driverId });
  const [first, second] = profiles;
  await page.getByRole('button', { name: '数据库', exact: true }).click();
  const tree = page.locator('.oc-db-tree');
  const connection = p => tree.locator(`[data-profile-id="${p.id}"]`);
  const row = p => connection(p).locator('.oc-db-connection');
  const table = (p, name = 'service_nodes') => connection(p).getByRole('button', { name, exact: true });
  const editor = page.getByRole('textbox', { name: 'SQL 编辑器', exact: true });
  async function query(sql, marker) {
    await editor.fill(sql);
    await page.getByRole('button', { name: '执行 SQL', exact: true }).click();
    await expect(page.getByRole('cell', { name: marker, exact: true })).toBeVisible();
  }
  await row(first).dblclick();
  await expect(editor).toBeVisible();
  await query("SELECT '来自连接一' AS source;", '来自连接一');
  await row(second).dblclick();
  await expect(page.getByRole('button', { name: `查询 1 · ${second.name}`, exact: true })).toBeVisible();
  await query("SELECT '来自连接二' AS source;", '来自连接二');
  await expect(table(first)).toBeVisible();
  await expect(table(second)).toBeVisible();
  await row(first).click();
  await expect(editor).toContainText('来自连接二');
  await expect(page.locator('.oc-db-context')).toContainText(second.name);
  checks.selectionDoesNotRetarget = true;
  await page.getByRole('button', { name: `查询 1 · ${first.name}`, exact: true }).click();
  await expect(editor).toContainText('来自连接一');
  await expect(page.getByRole('cell', { name: '来自连接一', exact: true })).toBeVisible();
  checks.queryDraftsAndResults = true;
  await table(first).dblclick();
  await expect(page.getByRole('cell', { name: 'order-api', exact: true })).toBeVisible();
  await table(second).dblclick();
  await expect(page.getByRole('button', { name: `service_nodes · ${first.name}`, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: `service_nodes · ${second.name}`, exact: true })).toBeVisible();
  checks.sameNameObjectsAreDistinct = true;
  await connection(first).getByRole('button', { name: `折叠连接 ${first.name}`, exact: true }).click();
  await expect(table(first)).not.toBeVisible();
  await expect(table(second)).toBeVisible();
  await connection(first).getByRole('button', { name: `展开连接 ${first.name}`, exact: true }).click();
  await expect(table(first)).toBeVisible();
  checks.independentExpansion = true;
  await page.getByRole('textbox', { name: '搜索数据库或表' }).fill('service_nodes');
  await expect(table(first)).toBeVisible();
  await expect(table(second)).toBeVisible();
  await expect(connection(first).getByRole('button', { name: 'job_runs', exact: true })).not.toBeVisible();
  await page.getByRole('textbox', { name: '搜索数据库或表' }).fill('');
  checks.filtering = true;
  await connection(first).getByRole('button', { name: '展开字段 service_nodes', exact: true }).click();
  await expect(connection(first).locator('.oc-db-columns').getByRole('button').filter({ hasText: 'service_name' })).toBeVisible();
  const before = await page.evaluate(() => window.explorerQueryCount);
  await table(first).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '生成 SELECT', exact: true }).click();
  await expect(editor).toContainText('FROM `opscopilot_review`.`service_nodes`');
  await expect(page.locator('.oc-db-context')).toContainText(first.name);
  expect(await page.evaluate(() => window.explorerQueryCount)).toBe(before);
  checks.templatesDoNotExecute = true;
  await editor.fill('SELECT ');
  await editor.press('Control+End');
  await connection(first).locator('.oc-db-columns').getByRole('button').filter({ hasText: 'service_name' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '插入当前查询', exact: true }).click();
  await expect(editor).toContainText('SELECT `service_name`');
  checks.columnInsertion = true;
  await table(second).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '复制完整名称', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('`opscopilot_review`.`service_nodes`');
  checks.copyQualifiedName = true;
  await table(second).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '插入当前查询', exact: true }).click();
  await expect(editor).toContainText('`opscopilot_review`.`service_nodes`');
  await expect(page.locator('.oc-db-context')).toContainText(second.name);
  checks.crossConnectionInsertion = true;
  await table(second).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '查看 DDL', exact: true }).click();
  await expect(page.locator('.oc-db-ddl')).toContainText('CREATE TABLE');
  await expect(page.locator('.oc-db-context')).toContainText(second.name);
  checks.contextTarget = true;
  await row(second).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '移动到分组…', exact: true }).click();
  await page.getByLabel('分组名称', { exact: true }).fill('对照环境');
  await page.getByRole('button', { name: '移动', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  expect((await page.evaluate(id => window.go.main.App.DatabaseProfiles().then(all => all.find(p => p.id === id)), second.id)).group).toBe('对照环境');
  await expect(table(second)).toBeVisible();
  checks.groupPersistence = true;
  await row(second).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '复制连接配置', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '添加数据库连接', exact: true });
  await expect(dialog.getByLabel('密码', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('密码', { exact: true })).toHaveAttribute('placeholder', '数据库密码');
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  checks.duplicateDoesNotCopySecrets = true;
  await page.getByRole('button', { name: `service_nodes · ${first.name}`, exact: true }).click();
  await page.screenshot({ path: `${evidence}/explorer-dark.png` });
  await table(first).click({ button: 'right' });
  const menuBounds = await page.getByRole('menu', { name: '数据库对象操作' }).boundingBox();
  expect(menuBounds.x).toBeGreaterThanOrEqual(0);
  expect(menuBounds.y + menuBounds.height).toBeLessThanOrEqual(833);
  await page.screenshot({ path: `${evidence}/explorer-menu.png` });
  await page.keyboard.press('Escape');
  await table(first).focus();
  await page.keyboard.press('Shift+F10');
  await expect(page.getByRole('menu')).toBeVisible();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).not.toBeVisible();
  checks.keyboardMenu = true;
  await page.setViewportSize({ width: 850, height: 833 });
  await expect(page.locator('.oc-db-context')).toBeVisible();
  await page.screenshot({ path: `${evidence}/explorer-narrow.png` });
  checks.noPageOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
  await page.screenshot({ path: `${evidence}/explorer-light.png` });
  expect(errors).toEqual([]);
  checks.consoleErrors = errors;
  await writeFile(`${evidence}/explorer-result.json`, JSON.stringify(checks, null, 2));
  console.log(JSON.stringify(checks));
} catch (error) {
  await page.screenshot({ path: `${evidence}/explorer-failure.png` }).catch(() => {});
  await writeFile(`${evidence}/explorer-failure.txt`, `${error.stack}\n${errors.join('\n')}`);
  throw error;
} finally {
  for (const id of sessions) await page.evaluate(id => window.go.main.App.DatabaseDisconnect(id), id).catch(() => {});
  await browser.close();
}
