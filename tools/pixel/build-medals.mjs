// Crop the AI atlas and resample full RGBA; never quantize colors or harden alpha.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { decodePng, encodePng } from './png.mjs';
import { extractFrame, visibleBounds } from './sheet.mjs';
import { sampleRgba } from './rgba.mjs';
import { medalKinds, medalTiers, validateMedalAssets } from '../checks/check-medal-assets.mjs';
const sheet = decodePng(readFileSync(resolve(process.argv[2]))), output = resolve(process.argv[3]);
if (sheet.width / 8 !== sheet.height / 4) throw new Error('Medal atlas requires eight by four square cells');
mkdirSync(output, { recursive: true });
const cells = medalTiers.flatMap((tier,row) => medalKinds.map((kind,column) => ({id:`medal-${kind}-${tier}`, image:extractFrame(sheet,column,row,8)})));
const bounds = cells.map(cell => visibleBounds(cell.image));
const scale = 116 / Math.max(...bounds.map(b => Math.max(b.right-b.left+1,b.bottom-b.top+1)));
const assets = {}, imports = [];
for (const [index, cell] of cells.entries()) {
  const b = bounds[index], cx=(b.left+b.right)/2, cy=(b.top+b.bottom)/2;
  const image = {width:128,height:128,data:new Uint8ClampedArray(128*128*4)};
  for (let y=0;y<128;y++) for(let x=0;x<128;x++) image.data.set(sampleRgba(cell.image,(x-63.5)/scale+cx,(y-63.5)/scale+cy),(y*128+x)*4);
  const file=`${cell.id}.png`;
  writeFileSync(resolve(output,file),encodePng(image,{adaptive:true}));
  assets[cell.id]=file; imports.push(`import asset${index} from './${file}';`);
}
const manifest = {version:1,id:'medals-v2',size:128,assets};
validateMedalAssets(manifest,output);
writeFileSync(resolve(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
writeFileSync(resolve(output,'catalog.ts'), '// Generated by tools/pixel/build-medals.mjs.\n'+imports.join('\n')+'\nexport const medalImages: Record<string,string> = {\n'+cells.map((cell,index)=>`  '${cell.id}': asset${index},`).join('\n')+'\n};\n');
console.log(`Saved ${cells.length} full-color medals`);
