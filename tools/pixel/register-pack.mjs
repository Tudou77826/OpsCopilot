// Static imports work in both Vite (desktop) and esbuild (Teams).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { validateCompanionPack } from '../checks/check-companion-assets.mjs';
const root = resolve(process.argv[2]), manifest = JSON.parse(readFileSync(resolve(root, 'manifest.json'), 'utf8'));
validateCompanionPack(manifest, root);
const rows = Object.entries(manifest.assets);
const imports = rows.map(([,asset],index)=>`import asset${index} from ${JSON.stringify('./'+asset.path)};`);
writeFileSync(resolve(root, 'catalog.ts'), '// Generated by tools/pixel/register-pack.mjs; change manifest and regenerate.\n'+imports.join('\n')+'\nexport const images: Record<string, string> = {\n'+rows.map(([id],index)=>`  ${JSON.stringify(id)}: asset${index},`).join('\n')+'\n};\n');
